#!/usr/bin/env bash
# Rebuild the prepared archive's vendor tree with only the SDK. Framework packages
# are provided by the host shop; shipping another Shopware/Symfony tree breaks older lanes.
set -euo pipefail

python3 - <<'PYTHON'
import json
from pathlib import Path

manifest = json.loads(Path('composer.json').read_text())
installed = json.loads(Path('vendor/composer/installed.json').read_text())
versions = {package['name']: package['version'] for package in installed['packages']}
bundle = json.loads(Path('vendor/ucp-php-sdk/symfony-bundle/composer.json').read_text())
platform = {
    name: versions[name] for name in bundle['require']
    if name != 'php' and not name.startswith(('ext-', 'ucp-php-sdk/'))
}
build = dict(manifest)
build['require'] = {
    'php': manifest['require']['php'],
    'ucp-php-sdk/symfony-bundle': versions['ucp-php-sdk/symfony-bundle'],
    'ucp-php-sdk/core': versions['ucp-php-sdk/core'],
}
build['replace'] = platform
build['config'] = {'vendor-dir': 'vendor'}
for key in ('require-dev', 'autoload-dev', 'scripts'):
    build.pop(key, None)
Path('.composer-bundled-sdk.json').write_text(json.dumps(build, indent=4) + '\n')

# Keep the published manifest's real requirements, without build-only source paths.
repositories = manifest.get('repositories', [])
def is_build_repository(repository):
    return isinstance(repository, dict) and repository.get('type') == 'path' and repository.get('url') in ('.sdk/core', './.sdk/core', '.sdk/symfony-bundle', './.sdk/symfony-bundle')
if isinstance(repositories, dict):
    manifest['repositories'] = {name: repository for name, repository in repositories.items() if not is_build_repository(repository)}
else:
    manifest['repositories'] = [repository for repository in repositories if not is_build_repository(repository)]
if not manifest['repositories']:
    del manifest['repositories']
Path('composer.json').write_text(json.dumps(manifest, indent=4) + '\n')
PYTHON

# This tree was generated by the preceding Composer step in the disposable build checkout.
rm -rf vendor
COMPOSER=.composer-bundled-sdk.json composer update --no-dev --no-scripts --no-interaction --prefer-dist

# Ship the SDK as plugin-owned PSR-4 instead of a second Composer runtime. Shopware registers
# a plugin's own autoload.psr-4 (KernelPluginLoader::registerPluginNamespaces), so the host's
# loader resolves Ucp\Sdk\... straight out of the bundled tree. The archive used to carry
# vendor/autoload.php and have the plugin require it: that registered a second Composer
# ClassLoader, whose vendor/composer/installed.php then appeared in
# InstalledVersions::getAllRawData() -- reported by FroshTools as "2 autoloaders registered"
# and able to shadow the host's own package versions.
# https://github.com/FriendsOfShopware/FroshTools/issues/469
python3 - <<'PYTHON'
import json
from pathlib import Path

manifest = json.loads(Path('composer.json').read_text())
psr4 = manifest.setdefault('autoload', {}).setdefault('psr-4', {})

# Read the prefixes off the installed packages instead of hardcoding them, so a namespace the
# SDK adds or renames cannot silently stop being autoloaded.
#
# One path per namespace, as a plain string: shopware-cli unmarshals autoload.psr-4 values into a
# Go string, and a JSON array makes every `shopware-cli extension` command fail outright with
# "cannot unmarshal array into Go struct field .autoload.psr-4". Shopware itself accepts either.
for package in ('core', 'symfony-bundle'):
    root = Path('vendor/ucp-php-sdk') / package
    autoload = json.loads((root / 'composer.json').read_text())['autoload']['psr-4']
    for namespace, paths in autoload.items():
        if isinstance(paths, str):
            paths = [paths]
        if len(paths) != 1:
            raise SystemExit(
                f'FAIL: ucp-php-sdk/{package} maps {namespace} to {len(paths)} paths. Only a single'
                ' path per namespace can be shipped; shopware-cli cannot read a list.'
            )
        psr4[namespace] = f'{root.as_posix()}/{paths[0].strip("/")}/'

Path('composer.json').write_text(json.dumps(manifest, indent=4) + '\n')
PYTHON

# installed.json stays: RequirementsValidator::validateShippedDependencies() reads it from the
# plugin's own vendor-dir to satisfy the ucp-php-sdk requires, and an archive without it fails
# to install with MissingRequirementException. Everything else Composer generated exists only
# to register an autoloader, so none of it ships.
rm -f vendor/autoload.php
find vendor/composer -mindepth 1 -maxdepth 1 ! -name installed.json -exec rm -rf {} +

rm .composer-bundled-sdk.json .composer-bundled-sdk.lock
touch .swag-agentic-commerce-bundled-sdk
