<?php

declare(strict_types=1);

use Composer\ClassMapGenerator\ClassMapGenerator;

/*
 * Writes lib/preload-classes.php for the archive: the plugin's classes (without src/Ucp/Test, which the archive
 * drops) and the bundled SDK's classes, each sorted.
 *
 * Usage: php bin/write-preload-class-list.php <plugin-dir> <autoload-file>
 *
 * <autoload-file> is a Composer autoloader that provides composer/class-map-generator, so the script does not
 * depend on a shop.
 */

if (3 !== $argc) {
    fwrite(\STDERR, "Usage: php bin/write-preload-class-list.php <plugin-dir> <autoload-file>\n");
    exit(1);
}

$pluginDir = realpath($argv[1]);
if (false === $pluginDir || !is_dir($pluginDir.'/src')) {
    fwrite(\STDERR, "No plugin directory with a src/ at {$argv[1]}\n");
    exit(1);
}

require $argv[2];

/**
 * @return list<class-string>
 */
function classesBelow(string $directory, ?string $excludedPattern = null): array
{
    $generator = new ClassMapGenerator();
    $generator->scanPaths($directory, $excludedPattern);
    $classes = array_keys($generator->getClassMap()->getMap());
    sort($classes, \SORT_STRING);

    return $classes;
}

$pluginClasses = classesBelow(
    $pluginDir.'/src',
    '{^'.preg_quote($pluginDir.'/src/Ucp/Test/', '}').'}',
);

$sdkClasses = [];
foreach (glob($pluginDir.'/lib/ucp-php-sdk/*/src', \GLOB_ONLYDIR) ?: [] as $sdkSourceDir) {
    $sdkClasses = [...$sdkClasses, ...classesBelow($sdkSourceDir)];
}
sort($sdkClasses, \SORT_STRING);

if ([] === $pluginClasses || [] === $sdkClasses) {
    fwrite(\STDERR, \sprintf(
        "Found %d plugin classes and %d SDK classes; neither list may be empty.\n",
        \count($pluginClasses),
        \count($sdkClasses),
    ));
    exit(1);
}

$renderList = static fn (array $classes): string => implode('', array_map(
    static fn (string $class): string => '        '.var_export($class, true).",\n",
    $classes,
));

$content = "<?php\n\ndeclare(strict_types=1);\n\n// Generated by bin/ci-bundle-sdk-into-archive.sh.\n\n"
    ."return [\n    'plugin' => [\n".$renderList($pluginClasses)."    ],\n"
    ."    'sdk' => [\n".$renderList($sdkClasses)."    ],\n];\n";

if (!is_dir($pluginDir.'/lib')) {
    mkdir($pluginDir.'/lib', 0o755, true);
}
file_put_contents($pluginDir.'/lib/preload-classes.php', $content);

printf("Wrote lib/preload-classes.php: %d plugin classes, %d SDK classes.\n", \count($pluginClasses), \count($sdkClasses));
